import fs from "fs";
import path from "path";

const JSON_DIR = "C:/KerisiAI/02MigrateFromOldKerisi/JSON_DATA";
const LEVEL_FILES = [
  "HIDDEN_PAGE_LEVEL2.json",
  "HIDDEN_PAGE_LEVEL3.json",
  "HIDDEN_PAGE_LEVEL4.json",
  "HIDDEN_PAGE_LEVEL5.json",
];

const ROUTER_DIR = "client/src/router";
const OUT_FILE = path.join(ROUTER_DIR, "kerisi-credit-control-hidden-routes.ts");

const routerIndex = fs.readFileSync("client/src/router/index.ts", "utf8");
const routeIds = new Set();
let m;
const pathRe = /path:\s*["']\/admin\/kerisi\/m\/(\d+)["']/g;
while ((m = pathRe.exec(routerIndex))) routeIds.add(m[1]);

for (const f of fs.readdirSync(ROUTER_DIR)) {
  if (!f.endsWith("-hidden-routes.ts")) continue;
  if (f === "kerisi-credit-control-hidden-routes.ts") continue;
  const src = fs.readFileSync(path.join(ROUTER_DIR, f), "utf8");
  const fnRe = /\b[a-zA-Z]+Hidden\(\s*(\d+)/g;
  while ((m = fnRe.exec(src))) routeIds.add(m[1]);
}

function isCreditControlMenu(menu) {
  return String(menu ?? "")
    .toLowerCase()
    .startsWith("credit control>");
}

function fallbackTitle(menu) {
  const parts = String(menu).split(">");
  const leaf = parts[parts.length - 1]?.trim();
  return leaf || "Credit Control";
}

const CC_HUB = { path: "/admin/kerisi/m/3066", label: "List of deposit" };
const CC_DEPOSIT = { path: "/admin/kerisi/m/1809", label: "Deposit" };

function pickRelated(menu) {
  const s = menu.toLowerCase();
  if (s.includes("refund")) return CC_DEPOSIT;
  if (s.includes("payment in advance") || s.includes("knockoff")) return CC_DEPOSIT;
  if (s.includes("debt monitoring") || s.includes("dca") || s.includes("lawyer"))
    return CC_HUB;
  return CC_HUB;
}

const rows = [];
for (const f of LEVEL_FILES) {
  const fp = path.join(JSON_DIR, f);
  if (!fs.existsSync(fp)) continue;
  const j = JSON.parse(fs.readFileSync(fp, "utf8"));
  for (const r of j) {
    if (!isCreditControlMenu(r.Menu)) continue;
    rows.push(r);
  }
}

const byMenu = new Map();
for (const r of rows) {
  const mid = String(r.MENUID);
  if (!byMenu.has(mid)) {
    byMenu.set(mid, {
      PAGETITLE: r.PAGETITLE,
      Menu: r.Menu,
    });
  }
}

const todo = [...byMenu.entries()]
  .filter(([mid]) => !routeIds.has(mid))
  .sort((a, b) => Number(a[0]) - Number(b[0]));

const header = `import type { RouteRecordRaw } from "vue-router";
import CreditControlLegacyPlaceholderView from "@/views/CreditControlLegacyPlaceholderView.vue";

const CC_LEGACY_DESC =
  "This legacy Credit Control screen is not reproduced in Kerisi20. Use Kerisi Classic for the full workflow.";

function ccHidden(
  menuId: number,
  name: string,
  title: string,
  legacyMenuPath: string,
  related?: { path: string; label: string },
): RouteRecordRaw {
  const breadcrumb = legacyMenuPath.replace(/>/g, " / ").replace(/\\s+/g, " ").trim();
  const rel = related ?? { path: "/admin/kerisi/m/3066", label: "List of deposit" };
  return {
    path: \`/admin/kerisi/m/\${menuId}\`,
    name,
    component: CreditControlLegacyPlaceholderView,
    props: {
      title,
      breadcrumb,
      description: CC_LEGACY_DESC,
      relatedPath: rel.path,
      relatedLabel: rel.label,
    },
    meta: { requiresAuth: true, title },
  };
}

/** HIDDEN_PAGE_LEVEL2–5: \`Menu\` starts with \`Credit Control>\`. Generated by scripts/generate-kerisi-credit-control-hidden-routes.mjs */
export const kerisiCreditControlHiddenRoutes: RouteRecordRaw[] = [
`;

const footer = `];
`;

const body = todo
  .map(([mid, d]) => {
    const rawTitle = String(d.PAGETITLE ?? "").replace(/\s+/g, " ").trim();
    const title = rawTitle || fallbackTitle(d.Menu);
    const menuPath = String(d.Menu).replace(/\s+/g, " ").trim();
    const titleJson = JSON.stringify(title);
    const menuJson = JSON.stringify(menuPath);
    const rel = pickRelated(menuPath);
    const relJson = `{ path: ${JSON.stringify(rel.path)}, label: ${JSON.stringify(rel.label)} }`;
    const name = `kerisi-cc-m-${mid}`;
    return `  ccHidden(${mid}, "${name}", ${titleJson}, ${menuJson}, ${relJson}),`;
  })
  .join("\n");

fs.writeFileSync(OUT_FILE, `${header}${body}\n${footer}`, "utf8");
console.log("Wrote", OUT_FILE, "routes:", todo.length);
