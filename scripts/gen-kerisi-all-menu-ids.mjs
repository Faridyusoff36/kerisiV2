/**
 * Reads client/src/config/kerisi-menu-migrated.ts and writes
 * client/src/config/kerisi-all-menu-ids.generated.ts
 *
 * Run: node scripts/gen-kerisi-all-menu-ids.mjs
 * Also invoked at the end of scripts/build-kerisi-menu.mjs.
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const migratedFile = path.join(root, "client/src/config/kerisi-menu-migrated.ts");
const outFile = path.join(root, "client/src/config/kerisi-all-menu-ids.generated.ts");

export function generateKerisiAllMenuIds() {
  if (!fs.existsSync(migratedFile)) {
    console.warn("gen-kerisi-all-menu-ids: skip —", migratedFile, "not found");
    return;
  }
  const text = fs.readFileSync(migratedFile, "utf8");
  const ids = new Set();
  for (const m of text.matchAll(/menuId:\s*(\d+)/g)) {
    ids.add(Number(m[1]));
  }
  const sorted = [...ids].sort((a, b) => a - b);
  const body = sorted.join(",\n  ");
  const content = `/** Auto-generated by scripts/gen-kerisi-all-menu-ids.mjs from kerisi-menu-migrated.ts — do not edit. */

export const KERISI_ALL_MENU_ID_COUNT = ${sorted.length} as const;

/**
 * Every \`menuId\` that appears in {@link KERISI_MENU_TREE} (kerisi-menu-migrated.ts).
 * Unlisted numeric paths still resolve via the router catch-all \`/admin/kerisi/m/:menuId\`.
 */
export const KERISI_ALL_MENU_IDS: readonly number[] = Object.freeze([
  ${body},
]);

const __kerisiAllMenuIdSet = new Set(KERISI_ALL_MENU_IDS);

export function isKerisiRegisteredMenuId(menuId: number): boolean {
  return __kerisiAllMenuIdSet.has(menuId);
}
`;
  fs.writeFileSync(outFile, content, "utf8");
  console.log("gen-kerisi-all-menu-ids: wrote", outFile, "unique ids:", sorted.length);
}

const thisFile = fileURLToPath(import.meta.url);
const isDirectRun =
  process.argv[1] && path.resolve(process.argv[1]) === path.resolve(thisFile);
if (isDirectRun) {
  generateKerisiAllMenuIds();
}
